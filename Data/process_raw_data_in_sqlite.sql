-- Build a unified event timeline and cohort-specific survival views.
-- Expected source table names are documented in Data/README.md.

DROP VIEW IF EXISTS timeline_engineered;
DROP VIEW IF EXISTS brca_survival_lstm_dataset;
DROP VIEW IF EXISTS crc_survival_lstm_dataset;
DROP VIEW IF EXISTS nsclc_survival_lstm_dataset;
DROP VIEW IF EXISTS panc_survival_lstm_dataset;
DROP VIEW IF EXISTS prostate_survival_lstm_dataset;

CREATE VIEW timeline_engineered AS

-- Diagnosis
SELECT PATIENT_ID, START_DATE, 0 AS EVENT_DURATION, EVENT_TYPE, 'AJCC_STAGE' AS EVENT_SUBTYPE,
       CAST(NULL AS REAL) AS VALUE_NUMERIC, AJCC AS VALUE_CATEGORICAL
FROM timeline_diagnosis WHERE AJCC IS NOT NULL AND AJCC != ''
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'CLINICAL_GROUP', CAST(NULL AS REAL), CLINICAL_GROUP
FROM timeline_diagnosis WHERE CLINICAL_GROUP IS NOT NULL AND CLINICAL_GROUP != ''
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'PATH_GROUP', CAST(NULL AS REAL), PATH_GROUP
FROM timeline_diagnosis WHERE PATH_GROUP IS NOT NULL AND PATH_GROUP != ''
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'STAGE_CDM_DERIVED', CAST(NULL AS REAL), STAGE_CDM_DERIVED
FROM timeline_diagnosis WHERE STAGE_CDM_DERIVED IS NOT NULL AND STAGE_CDM_DERIVED != ''
UNION ALL

-- Imaging and progression
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'IMAGING_CHEST', CAST(NULL AS REAL), PROCEDURE_TYPE
FROM timeline_cancer_presence WHERE CHEST = 1
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'IMAGING_ABDOMEN', CAST(NULL AS REAL), PROCEDURE_TYPE
FROM timeline_cancer_presence WHERE ABDOMEN = 1
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'IMAGING_PELVIS', CAST(NULL AS REAL), PROCEDURE_TYPE
FROM timeline_cancer_presence WHERE PELVIS = 1
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'IMAGING_HEAD', CAST(NULL AS REAL), PROCEDURE_TYPE
FROM timeline_cancer_presence WHERE HEAD = 1
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'IMAGING_OTHER', CAST(NULL AS REAL), PROCEDURE_TYPE
FROM timeline_cancer_presence WHERE OTHER = 1
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'TUMOR_SITE_' || TUMOR_SITE,
       CAST(NULL AS REAL), SOURCE_SPECIFIC
FROM timeline_tumor_sites WHERE TUMOR_SITE IS NOT NULL AND TUMOR_SITE != ''
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'IMAGING_PROGRESSION', CAST(NULL AS REAL), PROGRESSION
FROM timeline_progression WHERE PROGRESSION IS NOT NULL
UNION ALL

-- Laboratory measurements
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, TEST, CAST(RESULT AS REAL), LR_UNIT_MEASURE
FROM timeline_cea_labs
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, TEST, CAST(RESULT AS REAL), LR_UNIT_MEASURE
FROM timeline_psa_labs
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, TEST, CAST(RESULT AS REAL), LR_UNIT_MEASURE
FROM "timeline_ca_15-3_labs"
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, TEST, CAST(RESULT AS REAL), LR_UNIT_MEASURE
FROM "timeline_ca_19-9_labs"
UNION ALL

-- Treatment and procedures
SELECT PATIENT_ID, START_DATE, COALESCE(STOP_DATE - START_DATE, 0), EVENT_TYPE, SUBTYPE,
       CAST(NULL AS REAL), AGENT
FROM timeline_treatment
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'IS_INVESTIGATIVE',
       CASE WHEN RX_INVESTIGATIVE = 'Y' THEN 1.0 ELSE 0.0 END, CAST(NULL AS TEXT)
FROM timeline_treatment
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'IS_OROTOPICAL',
       CAST(FLAG_OROTOPICAL AS REAL), CAST(NULL AS TEXT)
FROM timeline_treatment
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, SUBTYPE, CAST(NULL AS REAL), CAST(NULL AS TEXT)
FROM timeline_radiation
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'PRIOR_MEDS_STATUS',
       CASE WHEN PRIOR_MED_TO_MSK = 'Prior medications to MSK' THEN 1.0 ELSE 0.0 END,
       CAST(NULL AS TEXT)
FROM timeline_prior_meds
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'PRIOR_MEDS_PROB',
       CAST(INFERRED_TX_PROB AS REAL), CAST(NULL AS TEXT)
FROM timeline_prior_meds
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, 'SURGERY_' || SUBTYPE,
       CAST(NULL AS REAL), CAST(NULL AS TEXT)
FROM timeline_surgery
UNION ALL

-- Pathology, specimen, and performance status
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, SUBTYPE, CAST(GLEASON_SCORE AS REAL), CAST(NULL AS TEXT)
FROM timeline_gleason
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, SUBTYPE, CAST(MMR_ABSENT AS REAL), CAST(NULL AS TEXT)
FROM timeline_mmr
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, SUBTYPE,
       CASE WHEN PDL1_POSITIVE = 'Yes' THEN 1.0 ELSE 0.0 END, CAST(NULL AS TEXT)
FROM timeline_pdl1
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, CAST(NULL AS TEXT),
       CAST(SEQ_DATE AS REAL), CAST(NULL AS TEXT)
FROM timeline_specimen_surgery
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, CAST(NULL AS TEXT),
       CAST(NULL AS REAL), CAST(NULL AS TEXT)
FROM timeline_specimen
UNION ALL
SELECT PATIENT_ID, START_DATE, 0, EVENT_TYPE, SUBTYPE, CAST(NULL AS REAL), CAST(NULL AS TEXT)
FROM timeline_performance_status;

-- SELECT t.*, b.* intentionally retains the source columns. Pandas may suffix the
-- duplicate PATIENT_ID column; the export step removes that duplicate defensively.
CREATE VIEW brca_survival_lstm_dataset AS
SELECT t.*, b.* FROM timeline_engineered AS t
INNER JOIN source_brca_dx_1st_seq_OS AS b ON t.PATIENT_ID = b.PATIENT_ID;

CREATE VIEW crc_survival_lstm_dataset AS
SELECT t.*, b.* FROM timeline_engineered AS t
INNER JOIN source_crc_dx_1st_seq_OS AS b ON t.PATIENT_ID = b.PATIENT_ID;

CREATE VIEW nsclc_survival_lstm_dataset AS
SELECT t.*, b.* FROM timeline_engineered AS t
INNER JOIN source_nsclc_dx_1st_seq_OS AS b ON t.PATIENT_ID = b.PATIENT_ID;

CREATE VIEW panc_survival_lstm_dataset AS
SELECT t.*, b.* FROM timeline_engineered AS t
INNER JOIN source_panc_dx_1st_seq_OS AS b ON t.PATIENT_ID = b.PATIENT_ID;

CREATE VIEW prostate_survival_lstm_dataset AS
SELECT t.*, b.* FROM timeline_engineered AS t
INNER JOIN source_prostate_dx_1st_seq_OS AS b ON t.PATIENT_ID = b.PATIENT_ID;
